#!/usr/bin/env python3
"""Generate (and check) the tutorial pages from the demo catalog.

Usage::

    python docs/_scripts/gen_tutorials.py            # write missing pages, refresh indexes
    python docs/_scripts/gen_tutorials.py --force    # also overwrite existing chapter pages
    python docs/_scripts/gen_tutorials.py --check    # verify docs match Window.py (CI)

* ``tutorials/book*/index.rst`` are regenerated on every run: they are pure
  data (chapter table + toctree).
* ``tutorials/book*/chapterNN.rst`` are written only when missing (or with
  ``--force``), so hand-written edits survive. A newly added demo therefore
  needs its section added by hand; ``--check`` tells you where.
* Chapter logos are copied from the package into ``_static/logos``.
* The one-paragraph introduction above each screenshot comes from
  ``intros.py``; ``--check`` fails if a demo has none.
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys

sys.path.insert(0, os.path.dirname(__file__))
from catalog import BOOKS, PACKAGE, Chapter, Demo, clean_description, iter_demos, load_catalog  # noqa: E402
from intros import INTROS  # noqa: E402

DOCS = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TUTORIALS = os.path.join(DOCS, "tutorials")
STATIC = os.path.join(DOCS, "_static")

GENERATED_NOTE = ".. Generated by docs/_scripts/gen_tutorials.py from nndesigndemos/Window.py.\n"


def underline(text: str, char: str) -> str:
    return f"{text}\n{char * len(text)}\n"


def demo_anchor(demo: Demo) -> str:
    return f"book{demo.book}-ch{demo.chapter:02d}-{demo.slug}"


def intro_key(demo: Demo) -> str:
    return f"book{demo.book}/ch{demo.chapter:02d}/{demo.slug}"


def demo_section(demo: Demo) -> str:
    """Heading, why-this-demo intro, screenshot, how to use it, controls, source."""
    lines = [f".. _{demo_anchor(demo)}:", "", underline(demo.name, "-")]
    intro = INTROS.get(intro_key(demo), "").strip()
    if intro:
        lines.append(" ".join(intro.split()))
        lines.append("")
    lines.append(f".. image:: /_static/{demo.screenshot}")
    lines.append(f"   :alt: {demo.name} demo window")
    lines.append("   :width: 100%")
    lines.append("")
    paragraphs = clean_description(demo.description)
    if paragraphs:
        lines.append("**How to use it**")
        lines.append("")
        for para in paragraphs:
            lines.append(para)
            lines.append("")
    if demo.controls:
        lines.append("**Controls**")
        lines.append("")
        for ctl in demo.controls:
            lines.append(f"- {ctl}")
        lines.append("")
    lines.append(f"**Source:** ``{demo.file}``")
    lines.append("")
    return "\n".join(lines)


def chapter_page(chapter: Chapter) -> str:
    heading = f"Chapter {chapter.number}: {chapter.title}"
    lines = [
        GENERATED_NOTE,
        f".. _book{chapter.book}-chapter{chapter.number:02d}:",
        "",
        underline(heading, "="),
        ".. contents:: Demos in this chapter",
        "   :local:",
        "   :depth: 1",
        "",
    ]
    for demo in chapter.demos:
        lines.append(demo_section(demo))
    return "\n".join(lines).rstrip() + "\n"


def book_index(book: int, chapters: list[Chapter]) -> str:
    info = BOOKS[book]
    heading = info["title"]
    total = sum(len(c.demos) for c in chapters)
    lines = [
        GENERATED_NOTE,
        f".. _book{book}-tutorials:",
        "",
        underline(heading, "="),
        f".. image:: /_static/logos/book{book}/cover.jpg",
        f"   :alt: {heading} cover",
        "   :width: 160px",
        "   :align: right",
        "",
        f"{total} demos across {len(chapters)} chapters. In the main menu press "
        f"**{info['menu_button']}**, then use the buttons along the bottom "
        f"({', '.join('**' + b + '**' for b in info['blocks'])}) to page through the chapters.",
        "",
        f"Book website: {info['url']}",
        "",
        ".. list-table::",
        "   :header-rows: 1",
        "   :widths: 12 58 30",
        "",
        "   * - Chapter",
        "     - Title",
        "     - Demos",
    ]
    for c in chapters:
        lines += [
            f"   * - :doc:`{c.number} <{c.slug}>`",
            f"     - {c.title}",
            f"     - {len(c.demos)}",
        ]
    lines += ["", ".. toctree::", "   :maxdepth: 1", "   :titlesonly:", ""]
    lines += [f"   {c.slug}" for c in chapters]
    return "\n".join(lines) + "\n"


def copy_logos(catalog) -> None:
    for book, chapters in catalog.items():
        info = BOOKS[book]
        dst_dir = os.path.join(STATIC, "logos", f"book{book}")
        os.makedirs(dst_dir, exist_ok=True)
        shutil.copyfile(os.path.join(PACKAGE, info["cover"]), os.path.join(dst_dir, "cover.jpg"))
        for c in chapters:
            src = os.path.join(PACKAGE, info["logo_dir"], f"{c.number}.svg")
            shutil.copyfile(src, os.path.join(dst_dir, f"{c.number}.svg"))


def generate(force: bool) -> None:
    catalog = load_catalog()
    copy_logos(catalog)
    written, kept = [], []
    for book, chapters in catalog.items():
        book_dir = os.path.join(TUTORIALS, f"book{book}")
        os.makedirs(book_dir, exist_ok=True)
        with open(os.path.join(book_dir, "index.rst"), "w", encoding="utf-8") as f:
            f.write(book_index(book, chapters))
        for c in chapters:
            path = os.path.join(book_dir, f"{c.slug}.rst")
            if os.path.exists(path) and not force:
                kept.append(path)
                continue
            with open(path, "w", encoding="utf-8") as f:
                f.write(chapter_page(c))
            written.append(path)
    print(f"wrote {len(written)} chapter pages, kept {len(kept)} existing, refreshed {len(catalog)} book indexes")


def check() -> int:
    """Exit non-zero if any demo lacks a tutorial section or a screenshot."""
    problems = []
    catalog = load_catalog()
    for book, chapters in catalog.items():
        for c in chapters:
            path = os.path.join(TUTORIALS, f"book{book}", f"{c.slug}.rst")
            if not os.path.exists(path):
                problems.append(f"missing page: {os.path.relpath(path, DOCS)}")
                continue
            text = open(path, encoding="utf-8").read()
            for d in c.demos:
                if f".. _{demo_anchor(d)}:" not in text:
                    problems.append(f"{os.path.relpath(path, DOCS)}: no section for demo {d.name!r} "
                                    f"(anchor {demo_anchor(d)})")
                if not INTROS.get(intro_key(d), "").strip():
                    problems.append(f"no intro paragraph for {intro_key(d)} in docs/_scripts/intros.py")
                shot = os.path.join(STATIC, d.screenshot)
                if not os.path.exists(shot):
                    problems.append(f"missing screenshot: _static/{d.screenshot}")
    for name in ("main_menu", "toc_book1", "toc_book2"):
        if not os.path.exists(os.path.join(STATIC, "screenshots", f"{name}.webp")):
            problems.append(f"missing screenshot: _static/screenshots/{name}.webp")
    total = sum(len(c.demos) for b in catalog.values() for c in b)
    if problems:
        print(f"{len(problems)} problem(s) across {total} demos:")
        for p in problems:
            print("  -", p)
        return 1
    print(f"OK: all {total} demos have a tutorial section and a screenshot")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify instead of generating")
    ap.add_argument("--force", action="store_true", help="overwrite existing chapter pages")
    args = ap.parse_args()
    if args.check:
        return check()
    generate(args.force)
    return 0


if __name__ == "__main__":
    sys.exit(main())
